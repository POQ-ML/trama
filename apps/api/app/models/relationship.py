"""Relationship model — typed edge between two Entity nodes.

MVP relationship types (PD-0002, accepted, closed set):
  topic_source   — topic  ↔ source
  project_event  — project ↔ event
  project_topic  — project ↔ topic

Valid (source_type, target_type) pairs per relationship type:
  topic_source  : (topic, source)  or  (source, topic)  — bidirectional
  project_event : (project, event) or  (event, project)
  project_topic : (project, topic) or  (topic, project)

These pairs are validated at the service layer; the DB enforces only
the closed enum values.

Status values (PD-0002): pending | confirmed | rejected.
'silenced' is NOT a valid status — correction is done via feedback/edit.

Self-relationships (source_id == target_id) are blocked by a CHECK constraint.
Duplicate (source_id, target_id, relationship_type) are blocked by a unique
constraint.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base

# Closed set — extend only via approved product decision (PD-0002).
VALID_RELATIONSHIP_TYPES: frozenset[str] = frozenset(
    {"topic_source", "project_event", "project_topic"}
)

# Closed set — 'silenced' is explicitly excluded (PD-0002).
VALID_STATUSES: frozenset[str] = frozenset({"pending", "confirmed", "rejected"})

# Valid (source entity_type, target entity_type) pairs per relationship type.
# Used by the service layer for validation; not enforced at DB level (would
# require a trigger — deferred to a later migration if needed).
VALID_TYPE_PAIRS: dict[str, frozenset[tuple[str, str]]] = {
    "topic_source": frozenset({("topic", "source"), ("source", "topic")}),
    "project_event": frozenset({("project", "event"), ("event", "project")}),
    "project_topic": frozenset({("project", "topic"), ("topic", "project")}),
}


class Relationship(Base):
    """Aresta tipada entre dois nós do mapa de conhecimento."""

    __tablename__ = "relationships"
    __table_args__ = (
        # No self-loops.
        CheckConstraint("source_id <> target_id", name="ck_relationship_no_self"),
        # Semantic uniqueness: the same typed edge cannot appear twice.
        UniqueConstraint(
            "source_id", "target_id", "relationship_type",
            name="uq_relationship_source_target_type",
        ),
        # Closed enum enforced in DB.
        CheckConstraint(
            "relationship_type IN ('topic_source', 'project_event', 'project_topic')",
            name="ck_relationship_type_valid",
        ),
        CheckConstraint(
            "status IN ('pending', 'confirmed', 'rejected')",
            name="ck_relationship_status_valid",
        ),
        Index("ix_relationships_source_id", "source_id"),
        Index("ix_relationships_target_id", "target_id"),
        Index("ix_relationships_status", "status"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )

    source_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("entities.id", ondelete="CASCADE"),
        nullable=False,
    )
    target_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("entities.id", ondelete="CASCADE"),
        nullable=False,
    )

    # Closed enum: topic_source | project_event | project_topic (PD-0002).
    relationship_type: Mapped[str] = mapped_column(String(50), nullable=False)

    # Human-readable justification for why this relationship was proposed.
    # May be generated by scoring logic; NOT treated as evidence by itself.
    justification: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Default: pending — must be confirmed before display (PD-0002, rule 4).
    status: Mapped[str] = mapped_column(
        String(20), nullable=False, default="pending", server_default="pending"
    )

    # Optional scoring signal (recency + entity overlap + source type, v1).
    # Nullable: not all relationships are scored at creation time.
    score: Mapped[float | None] = mapped_column(Float, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    # Relationships (ORM)
    source_entity: Mapped["Entity"] = relationship(  # noqa: F821
        "Entity",
        back_populates="outgoing_relationships",
        foreign_keys=[source_id],
    )
    target_entity: Mapped["Entity"] = relationship(  # noqa: F821
        "Entity",
        back_populates="incoming_relationships",
        foreign_keys=[target_id],
    )
    evidences: Mapped[list["Evidence"]] = relationship(  # noqa: F821
        "Evidence",
        back_populates="relationship",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:  # pragma: no cover
        return (
            f"<Relationship id={self.id} type={self.relationship_type!r} "
            f"status={self.status!r}>"
        )
